export function getGroupTitle(group: BudgetGroup, lang: Language): string {
  const t = TRANSLATIONS[lang];
  switch (group) {
    case 'income':
      return t.groupIncome;
    case 'bills':
      return t.groupBills;
    case 'variable':
      return t.groupVariable;
    case 'savings':
      return t.groupSavings;
  }
}
