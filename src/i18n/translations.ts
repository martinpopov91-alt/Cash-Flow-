export function formatMonthTitle(monthKey: string, lang: Language): string {
  const [yStr, mStr] = monthKey.split('-');
  const monthIdx = Math.max(0, Math.min(11, Number(mStr) - 1));
  return `${MONTH_NAMES[lang][monthIdx]} ${yStr}`;
}

export function getItemLabel(item: BudgetLineItem, lang: Language): string {
  return lang === 'bg' ? item.labelBg || item.labelEn : item.labelEn || item.labelBg;
}

